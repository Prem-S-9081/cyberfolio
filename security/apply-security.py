#!/usr/bin/env python3
"""Single source of truth for the site's security policy.

Reads security/csp.txt and:
  1. writes the CSP + Referrer-Policy <meta> tags into docs/index.html and docs/404.html
  2. writes cloudflare/response-headers.txt (the same CSP plus the header-only protections)

Usage:  python security/apply-security.py          apply
        python security/apply-security.py --check  exit 1 if anything is out of date
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent   # repo root
SITE = ROOT / "docs"                                    # the published website
REFERRER = "strict-origin-when-cross-origin"
HEADER_ONLY_CSP = ["frame-ancestors 'none'"]          # not allowed in a <meta> CSP
EXTRA_HEADERS = [
    ("X-Content-Type-Options", "nosniff"),
    ("Referrer-Policy", REFERRER),
    ("Strict-Transport-Security", "max-age=15552000"),
    ("Permissions-Policy", "camera=(), microphone=(), geolocation=(), payment=(), usb=()"),
    ("Cross-Origin-Opener-Policy", "same-origin"),
]
PAGES = ["index.html", "404.html"]
START, END = "<!-- security:start (generated by security/apply-security.py) -->", "<!-- security:end -->"


def directives():
    lines = (ROOT / "security" / "csp.txt").read_text(encoding="utf-8").splitlines()
    return [l.strip() for l in lines if l.strip() and not l.lstrip().startswith("#")]


def meta_block():
    csp = "; ".join(directives())
    return (f'{START}\n    <meta http-equiv="Content-Security-Policy" content="{csp}">\n'
            f'    <meta name="referrer" content="{REFERRER}">\n    {END}')


def headers_text():
    csp = "; ".join(directives() + HEADER_ONLY_CSP)
    rows = [("Content-Security-Policy", csp)] + EXTRA_HEADERS
    return "".join(f"{k}: {v}\n" for k, v in rows)


def apply_page(text):
    block = meta_block()
    if START in text:
        return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block, text, flags=re.S)
    return re.sub(r"(<head>\s*<meta charset=[^>]*>)", lambda m: m.group(1) + "\n    " + block, text, count=1)


def main():
    check = "--check" in sys.argv
    stale = []
    for name in PAGES:
        p = SITE / name
        old = p.read_text(encoding="utf-8"); new = apply_page(old)
        if old != new:
            stale.append(name)
            if not check: p.write_text(new, encoding="utf-8")
    hp = ROOT / "cloudflare" / "response-headers.txt"
    want = headers_text()
    if not hp.exists() or hp.read_text(encoding="utf-8") != want:
        stale.append("cloudflare/response-headers.txt")
        if not check:
            hp.parent.mkdir(exist_ok=True); hp.write_text(want, encoding="utf-8")
    if check:
        print("out of date: " + ", ".join(stale) if stale else "security policy is in sync")
        sys.exit(1 if stale else 0)
    print("updated: " + ", ".join(stale) if stale else "already in sync")


if __name__ == "__main__":
    main()
